#!/usr/bin/env python3
"""Write the accuracy-audit table into docs/DATA.md (between the AUDIT markers).

One row per distinct claim: an item's capability edge (video Gbps or power W, grouped across
identical ports), a device's charging threshold, or a standard's rate. Results default to
'Verified' for high confidence and 'Verified source; value inferred' for medium/low, unless
data/src/audit.json records something else.

Usage: python3 scripts/build_audit.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "src"
DOC = ROOT / "docs" / "DATA.md"
BEGIN, END = "<!-- AUDIT:BEGIN (generated by scripts/build_audit.py) -->", "<!-- AUDIT:END -->"


def load(n):
    return json.loads((SRC / n).read_text(encoding="utf-8"))


def table():
    items = load("items.json")["items"]
    sources = {s["id"]: s for s in load("sources.json")}
    standards = {s["id"]: s for s in load("standards.json")}
    audit = load("audit.json")
    date = audit["checked"]
    search_only = set(audit["search_only"])
    resourced = set(audit.get("resourced_from_class", []))

    def link(sid):
        s = sources[sid]
        return f"[{s['publisher']}: {s['title']}]({s['url']})"

    def checked(sid):
        return f"{date}, {'search extract' if sid in search_only else 'page fetched'}"

    def default(conf, sid):
        base = "Verified" if conf == "high" else ("Verified source; value partly inferred" if conf == "medium" else "Source confirms the feature; value assumed")
        if sid in search_only:
            base += " (site blocks scripted fetch)"
        return base

    rows = []
    for st in standards.values():
        rate = f"{st['data_gbps']} Gbps data" if st.get("data_gbps") is not None else f"{st['watts']} W"
        rows.append(("standard " + st["id"], rate, st["source"], st["confidence"], audit["edges"].get(f"std|{st['id']}")))
    for it in items:
        seen = {}
        for dom in ("video", "power"):
            for e in it.get(dom, []):
                val = e.get("standard") or (f"{e['watts']} W" if "watts" in e else "")
                key = (dom, val, e["source"], e["confidence"])
                seen.setdefault(key, []).append(f"{e['from']}→{e['to']}")
        for (dom, val, sid, conf), hops in seen.items():
            if dom == "video":
                claim = f"video {', '.join(hops)}: {val} ({standards[val]['data_gbps']} Gbps)"
            else:
                w = val if val.endswith("W") else (f"{standards[val]['watts']} W ({val})" if val else "charges here")
                claim = f"power {', '.join(hops)}: {w}"
            key = f"{it['id']}|{dom}|{val.replace(' W', '') if val.endswith(' W') else val}"
            res = audit["edges"].get(key)
            if res is None and key in resourced:
                res = ("RE-SOURCED: was the repo-internal 'class-assumption' note (a private URL); now the public page of the "
                       "standard the class claims. Limit unchanged.")
            rows.append((it["id"], claim, sid, conf, res))
        if it.get("pd_source") and (it.get("pd_recommended_w") or it.get("pd_fast_w")):
            claim = f"charging threshold: recommended {it.get('pd_recommended_w') or 'n/a'} W, fast {it.get('pd_fast_w') or 'n/a'} W"
            rows.append((it["id"], claim, it["pd_source"], "medium" if it["pd_source"] in search_only else "high", None))
    out = ["| Item | Claim | Source | Checked | Confidence | Result |", "|---|---|---|---|---|---|"]
    for item, claim, sid, conf, res in rows:
        out.append(f"| `{item}` | {claim} | {link(sid)} | {checked(sid)} | {conf} | {res or default(conf, sid)} |")
    return "\n".join(out), len(rows)


def main():
    body, n = table()
    doc = DOC.read_text(encoding="utf-8")
    a, b = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    new = doc[:a] + "\n" + body + "\n" + doc[b:]
    if "--check" in sys.argv:
        sys.exit(0 if new == doc else "docs/DATA.md audit table is stale: run python3 scripts/build_audit.py")
    DOC.write_text(new, encoding="utf-8")
    print(f"wrote {n} audit rows")


if __name__ == "__main__":
    main()
