#!/usr/bin/env python3
"""Generate the self-contained skill folder agent/skills/pack-my-bag/ from the sources of truth:
queries/*.cypher, agent/cypher/*.cypher, agent/schemas/*.json and agent/prompts/*.md.

  python3 scripts/build_agent_docs.py          # write
  python3 scripts/build_agent_docs.py --check  # exit 1 if the skill folder is stale (used by tests)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent_lib  # noqa: E402
import mcp_server  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "agent" / "skills" / "pack-my-bag"


def render():
    files = {}
    parts = ["# Weakest Link recipes, check queries and schemas",
             "",
             "Generated by `scripts/build_agent_docs.py`; do not edit by hand. The same recipes are stored as",
             "`:Recipe` nodes in the writable `weakest-link-mybag` store, so you can also fetch them with",
             "`MATCH (r:Recipe {name: $name}) RETURN r.cypher`.",
             "",
             "Read recipes go to `read_cypher`, write recipes to `write_cypher`. Pass the text verbatim and put",
             "your values in `parameters`.",
             ""]
    for name, kind, path, desc, example in mcp_server.RECIPES:
        import json
        parts += [f"## `{name}` ({kind})", "", desc, "", "Example `parameters`:", "",
                  "```json", json.dumps(example, indent=2), "```", "",
                  "```cypher", path.read_text(encoding="utf-8").rstrip(), "```", ""]
    parts += ["## Check queries (run after a write)", "",
              "Venue (`parameters: {\"id\": \"<venue id>\"}`):", "", "```cypher", agent_lib.VENUE_CHECK.strip(), "```", "",
              "Item (`parameters: {\"id\": \"<item id>\"}`):", "", "```cypher", agent_lib.ITEM_CHECK.strip(), "```", ""]
    for schema in sorted((ROOT / "agent" / "schemas").glob("*.json")):
        parts += [f"## Schema `{schema.name}`", "", "```json", schema.read_text(encoding="utf-8").rstrip(), "```", ""]
    files[SKILL / "CYPHER.md"] = "\n".join(parts)
    for prompt in sorted((ROOT / "agent" / "prompts").glob("*.md")):
        files[SKILL / "prompts" / prompt.name] = prompt.read_text(encoding="utf-8")
    return files


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in render().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale:", ", ".join(map(str, stale)))
        return 1
    print("up to date" if check else f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
